package com.laundry.iot.service;

import com.laundry.iot.config.IotProvisioningProperties;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import javax.crypto.Cipher;
import javax.crypto.Mac;
import javax.crypto.spec.GCMParameterSpec;
import javax.crypto.spec.SecretKeySpec;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.MessageDigest;
import java.security.SecureRandom;
import java.util.Base64;
import java.util.HexFormat;
import java.util.regex.Pattern;

/**
 * Key derivation and constant-time checks for device provisioning.
 *
 * <pre>
 * setupKey     = 6-digit pairing code generated by the ESP32 on first boot, shown on the
 *                device screen (QR + digits) and scanned or typed by the admin
 * proof        = HMAC(setupKey, deviceId + ":" + nonce)                                  (hex, sent by ESP32)
 * mqttPassword = HMAC(deviceSecretKey, "mqtt:" + deviceId + ":" + credentialVersion)    (base64url)
 * </pre>
 *
 * <p>The setup key is held only while a pairing session is open, encrypted with
 * AES-GCM under a key derived from {@code deviceSecretKey}, and wiped on activation.
 *
 * <p>Six digits are enough against online guessing: the code is single-use, only
 * valid inside a 10-minute pairing an admin opened, and the pairing is aborted
 * after {@code maxPairingAttempts} wrong proofs. A proof sniffed on plain HTTP
 * could be brute-forced offline, so deployments must use HTTPS (on HTTP the MQTT
 * password in the activation reply is exposed anyway).
 */
@Service
@RequiredArgsConstructor
public class DeviceSecretService {

    private static final Pattern SETUP_KEY = Pattern.compile("^[0-9]{6}$");
    private static final int GCM_IV_BYTES = 12;
    private static final int GCM_TAG_BITS = 128;
    private static final HexFormat HEX = HexFormat.of();

    private final IotProvisioningProperties properties;
    private final SecureRandom random = new SecureRandom();

    /** Strips the separators an admin may type ("123 456", "123-456"). */
    public static String normalizeSetupKey(String raw) {
        return raw == null ? "" : raw.replaceAll("[\\s-]", "").toUpperCase();
    }

    public boolean isValidSetupKey(String normalized) {
        return normalized != null && SETUP_KEY.matcher(normalized).matches();
    }

    public String mqttPassword(String deviceId, int credentialVersion) {
        return Base64.getUrlEncoder().withoutPadding()
                .encodeToString(hmac(masterKey(), "mqtt:" + deviceId + ":" + credentialVersion));
    }

    /** Verify the ESP32's HMAC proof that it holds the setup key the admin scanned. */
    public boolean verifyProof(String deviceId, String setupKey, String nonce, String proofHex) {
        if (setupKey == null || proofHex == null || proofHex.length() != 64) return false;
        byte[] expected = hmac(setupKey.getBytes(StandardCharsets.US_ASCII), deviceId + ":" + nonce);
        byte[] provided;
        try {
            provided = HEX.parseHex(proofHex.toLowerCase());
        } catch (IllegalArgumentException e) {
            return false;
        }
        return MessageDigest.isEqual(expected, provided);
    }

    /** AES-GCM; output is base64(iv ‖ ciphertext ‖ tag). */
    public String encryptSetupKey(String setupKey) {
        try {
            byte[] iv = new byte[GCM_IV_BYTES];
            random.nextBytes(iv);
            Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
            cipher.init(Cipher.ENCRYPT_MODE, setupKeyCipherKey(), new GCMParameterSpec(GCM_TAG_BITS, iv));
            byte[] sealed = cipher.doFinal(setupKey.getBytes(StandardCharsets.US_ASCII));
            return Base64.getEncoder().encodeToString(ByteBuffer.allocate(iv.length + sealed.length)
                    .put(iv).put(sealed).array());
        } catch (GeneralSecurityException e) {
            throw new IllegalStateException(e);
        }
    }

    /** Returns null when the value is missing or was not sealed with the current master key. */
    public String decryptSetupKey(String sealed) {
        if (sealed == null || sealed.isBlank()) return null;
        try {
            byte[] all = Base64.getDecoder().decode(sealed);
            if (all.length <= GCM_IV_BYTES) return null;
            Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
            cipher.init(Cipher.DECRYPT_MODE, setupKeyCipherKey(),
                    new GCMParameterSpec(GCM_TAG_BITS, all, 0, GCM_IV_BYTES));
            byte[] plain = cipher.doFinal(all, GCM_IV_BYTES, all.length - GCM_IV_BYTES);
            return new String(plain, StandardCharsets.US_ASCII);
        } catch (IllegalArgumentException | GeneralSecurityException e) {
            return null;
        }
    }

    public String newNonce() {
        byte[] bytes = new byte[16];
        random.nextBytes(bytes);
        return HEX.formatHex(bytes);
    }

    private SecretKeySpec setupKeyCipherKey() {
        return new SecretKeySpec(hmac(masterKey(), "setup-key-encryption"), "AES");
    }

    private byte[] masterKey() {
        String key = properties.getDeviceSecretKey();
        if (key == null || key.length() < 32) {
            throw new IllegalStateException(
                    "IOT_DEVICE_SECRET_KEY is not configured (needs at least 32 characters)");
        }
        return key.getBytes(StandardCharsets.UTF_8);
    }

    private static byte[] hmac(byte[] key, String message) {
        try {
            Mac mac = Mac.getInstance("HmacSHA256");
            mac.init(new SecretKeySpec(key, "HmacSHA256"));
            return mac.doFinal(message.getBytes(StandardCharsets.UTF_8));
        } catch (GeneralSecurityException e) {
            throw new IllegalStateException(e);
        }
    }
}
